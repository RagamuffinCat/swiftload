#!/usr/bin/env bash
# Builds libdeflate for all six platforms from one Linux or macOS machine with Zig, into
# common/src/main/resources/natives, and writes natives.properties. The output is reproducible:
# the hashes must match the committed ones.
#
# Needs git, python3 (Zig comes from PyPI into a venv) and sha256sum or shasum. libdeflate picks
# its SIMD code at runtime, so the baseline targets lose nothing.
set -euo pipefail

LIBDEFLATE_TAG="${LIBDEFLATE_TAG:-v1.26}"
ZIG_VERSION="${ZIG_VERSION:-0.17.0}"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${WORK:-$ROOT/natives/.work}"
OUT="${OUT:-$ROOT/common/src/main/resources/natives}"

# platform-dir | zig target | output file name
TARGETS=(
  "windows-x86_64|x86_64-windows-gnu|deflate.dll"
  "windows-aarch64|aarch64-windows-gnu|deflate.dll"
  "linux-x86_64|x86_64-linux-gnu.2.17|libdeflate.so"
  "linux-aarch64|aarch64-linux-gnu.2.17|libdeflate.so"
  "macos-x86_64|x86_64-macos.11.0|libdeflate.dylib"
  "macos-aarch64|aarch64-macos.11.0|libdeflate.dylib"
)

SOURCES=(
  lib/adler32.c lib/crc32.c lib/utils.c
  lib/deflate_compress.c lib/deflate_decompress.c
  lib/zlib_compress.c lib/zlib_decompress.c
  lib/gzip_compress.c lib/gzip_decompress.c
  lib/x86/cpu_features.c lib/arm/cpu_features.c
)

mkdir -p "$WORK"


if [ ! -x "$WORK/zigenv/bin/python" ]; then
  python3 -m venv "$WORK/zigenv"
  "$WORK/zigenv/bin/pip" install -q "ziglang==$ZIG_VERSION"
fi
ZIG=("$WORK/zigenv/bin/python" -m ziglang)
echo ">> zig $("${ZIG[@]}" version)"


SRC="$WORK/libdeflate-$LIBDEFLATE_TAG"
if [ ! -d "$SRC" ]; then
  git clone --depth 1 --branch "$LIBDEFLATE_TAG" https://github.com/ebiggers/libdeflate.git "$SRC"
fi
echo ">> libdeflate $(git -C "$SRC" describe --tags 2>/dev/null || echo "$LIBDEFLATE_TAG")"

sha() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }

MANIFEST="$OUT/natives.properties"
mkdir -p "$OUT"
{
  echo "# Generated by natives/build-libdeflate.sh -- do not edit by hand."
  echo "libdeflate.version=$LIBDEFLATE_TAG"
  echo "zig.version=$ZIG_VERSION"
} > "$MANIFEST"

for t in "${TARGETS[@]}"; do
  IFS='|' read -r plat target file <<< "$t"
  dest="$OUT/$plat"
  mkdir -p "$dest"
  echo ">> $plat ($target)"
  # Fixed install name and soname, so the build path isn't embedded
  case "$plat" in
    macos-*) extra=(-Wl,-install_name,@rpath/$file) ;;
    linux-*) extra=(-Wl,-soname,$file) ;;
    *)       extra=() ;;
  esac
  ( cd "$SRC" && "${ZIG[@]}" cc -target "$target" \
      -O3 -DNDEBUG -DLIBDEFLATE_DLL -fvisibility=hidden -fPIC -shared -s \
      -ffile-prefix-map="$SRC"=. "${extra[@]}" \
      -I. "${SOURCES[@]}" -o "$dest/$file" )
  # Only the library itself is shipped, not the import libraries next to it
  find "$dest" -type f ! -name "$file" -delete
  echo "$plat=$file sha256=$(sha "$dest/$file")" >> "$MANIFEST"
done

echo ">> wrote $MANIFEST"
cat "$MANIFEST"
